'use client'

import { useRef, useState } from 'react'
import { getFixtureCardData, type FixtureCardData } from './fixtureCardActions'

function fmt(dateStr: string) {
  return new Date(dateStr).toLocaleDateString('en-GB', {
    weekday: 'long', day: 'numeric', month: 'long', year: 'numeric',
  })
}

function fmtTime(t: string | null) {
  if (!t) return 'TBC'
  const [h, m] = t.split(':')
  const d = new Date()
  d.setHours(Number(h), Number(m))
  return d.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' })
}

function Row({ label, value }: { label: string; value: string | null | undefined }) {
  if (!value) return null
  return (
    <tr>
      <td style={{ paddingRight: 16, paddingTop: 4, paddingBottom: 4, color: '#6b7280', fontSize: 13, whiteSpace: 'nowrap', verticalAlign: 'top', fontWeight: 500 }}>{label}</td>
      <td style={{ paddingTop: 4, paddingBottom: 4, color: '#111827', fontSize: 13, verticalAlign: 'top' }}>{value}</td>
    </tr>
  )
}

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div style={{ marginBottom: 20 }}>
      <div style={{ fontSize: 11, fontWeight: 800, letterSpacing: '0.06em', textTransform: 'uppercase', color: '#374151', marginBottom: 8, paddingBottom: 6, borderBottom: '2px solid #e5e7eb' }}>
        {title}
      </div>
      {children}
    </div>
  )
}

function FixtureCard({ data }: { data: FixtureCardData }) {
  const videoingText = data.videoingAllowed === true ? 'Allowed' : data.videoingAllowed === false ? 'Not allowed' : null

  return (
    <div style={{ width: 640, backgroundColor: '#ffffff', fontFamily: '-apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif', padding: 36, boxSizing: 'border-box' }}>
      {/* Header row: text left, crest right */}
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 24 }}>
        <div>
          <div style={{ fontSize: 11, fontWeight: 700, letterSpacing: '0.1em', textTransform: 'uppercase', color: '#991b1b', marginBottom: 4 }}>
            Fixture Information
          </div>
          <div style={{ fontSize: 22, fontWeight: 800, color: '#111827', lineHeight: 1.2 }}>
            {data.teamName}
          </div>
          <div style={{ fontSize: 14, color: '#6b7280', marginTop: 2 }}>
            vs {data.opponentName}
          </div>
        </div>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src="/crest.png" alt="AFC Green Court" style={{ height: 80, width: 'auto' }} crossOrigin="anonymous" />
      </div>

      <div style={{ height: 1, backgroundColor: '#e5e7eb', marginBottom: 22 }} />

      <Section title="Match details">
        <table style={{ borderCollapse: 'collapse' }}>
          <tbody>
            <Row label="Date" value={fmt(data.date)} />
            <Row label="Kick-off" value={fmtTime(data.kickoffTime)} />
            <Row label="Competition" value={data.competition} />
            <Row label="Venue" value={data.venueName ?? null} />
            <Row label="Address" value={data.venueAddress} />
            <Row label="Opp. colours" value={data.oppColours} />
            <Row label="Videoing" value={videoingText} />
          </tbody>
        </table>
      </Section>

      {/* Team manager before fixture secretary */}
      {(data.oppManagerName || data.oppManagerEmail || data.oppManagerPhone) && (
        <Section title={`${data.opponentName} - Team Manager`}>
          <table style={{ borderCollapse: 'collapse' }}>
            <tbody>
              <Row label="Name" value={data.oppManagerName} />
              <Row label="Email" value={data.oppManagerEmail} />
              <Row label="Phone" value={data.oppManagerPhone} />
            </tbody>
          </table>
        </Section>
      )}

      {(data.oppFixSecName || data.oppFixSecEmail || data.oppFixSecPhone) && (
        <Section title={`${data.opponentName} - Fixture Secretary`}>
          <table style={{ borderCollapse: 'collapse' }}>
            <tbody>
              <Row label="Name" value={data.oppFixSecName} />
              <Row label="Email" value={data.oppFixSecEmail} />
              <Row label="Phone" value={data.oppFixSecPhone} />
            </tbody>
          </table>
        </Section>
      )}

      {data.leagueNotes && (
        <Section title="Venue notes">
          <div style={{ fontSize: 12, color: '#374151', lineHeight: 1.6, whiteSpace: 'pre-wrap' }}>
            {data.leagueNotes}
          </div>
        </Section>
      )}

      <div style={{ marginTop: 24, paddingTop: 12, borderTop: '1px solid #e5e7eb', fontSize: 11, color: '#9ca3af', textAlign: 'right' }}>
        AFC Green Court · Generated by Merlin
      </div>
    </div>
  )
}

export default function FixtureCardDownload({ fixtureId, teamId }: { fixtureId: string; teamId: string }) {
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [cardData, setCardData] = useState<FixtureCardData | null>(null)
  const cardRef = useRef<HTMLDivElement>(null)

  async function handleDownload() {
    setLoading(true)
    setError(null)

    const { data, error: fetchError } = await getFixtureCardData(fixtureId, teamId)
    if (fetchError || !data) {
      setError(fetchError ?? 'Failed to load fixture data')
      setLoading(false)
      return
    }

    // Render the card into the hidden div, then capture it
    setCardData(data)

    // Wait for React to paint the card
    await new Promise(resolve => setTimeout(resolve, 150))

    if (!cardRef.current) {
      setError('Render target not found')
      setLoading(false)
      return
    }

    try {
      const html2canvas = (await import('html2canvas')).default
      const canvas = await html2canvas(cardRef.current, {
        scale: 2,
        useCORS: true,
        backgroundColor: '#ffffff',
        logging: false,
      })

      const link = document.createElement('a')
      const slug = `${data.teamName.replace(/\s+/g, '-')}-vs-${data.opponentName.replace(/\s+/g, '-')}-${data.date}`
      link.download = `${slug}.png`
      link.href = canvas.toDataURL('image/png')
      link.click()
    } catch {
      setError('Failed to generate image')
    }

    setLoading(false)
  }

  return (
    <>
      {/* Hidden render target — always mounted so ref is stable */}
      <div style={{ position: 'fixed', top: -9999, left: -9999, zIndex: -1, pointerEvents: 'none' }} aria-hidden="true">
        <div ref={cardRef}>
          {cardData && <FixtureCard data={cardData} />}
        </div>
      </div>

      <button
        type="button"
        onClick={handleDownload}
        disabled={loading}
        className="flex items-center gap-2 border border-gray-300 text-gray-700 hover:bg-gray-50 text-sm font-semibold px-4 py-2 rounded-lg transition disabled:opacity-50"
      >
        {loading ? (
          <>
            <svg className="w-4 h-4 animate-spin" fill="none" viewBox="0 0 24 24">
              <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" />
              <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8v8z" />
            </svg>
            Generating…
          </>
        ) : (
          <>
            <svg className="w-4 h-4" fill="none" stroke="currentColor" strokeWidth="2" viewBox="0 0 24 24">
              <path d="M4 16v2a2 2 0 002 2h12a2 2 0 002-2v-2M7 10l5 5 5-5M12 15V3" strokeLinecap="round" strokeLinejoin="round" />
            </svg>
            Download info card
          </>
        )}
      </button>

      {error && <p className="text-xs text-red-600 mt-1">{error}</p>}
    </>
  )
}
